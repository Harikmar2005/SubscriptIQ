import unittest
from datetime import datetime, timezone, timedelta
from sqlalchemy import create_engine
from sqlalchemy.orm import sessionmaker
from app.database.base import Base
from app.models.subscription import Customer, Subscription, SubscriptionPlan, Invoice, Payment
from app.services.subscription_service import SubscriptionLifecycleEngine
from app.services.payment_service import PaymentProcessingService

class TestMultiTenantIsolation(unittest.TestCase):
    def setUp(self):
        self.engine = create_engine("sqlite:///:memory:")
        Base.metadata.create_all(bind=self.engine)
        self.Session = sessionmaker(bind=self.engine)
        self.db = self.Session()

        # Seed data for Tenant A (Alpha)
        self.plan_a = SubscriptionPlan(
            id="plan-a",
            tenant_id="tenant-alpha",
            name="Alpha Plan",
            code="alpha",
            monthly_price=1000,
            annual_price=10000
        )
        self.cust_a = Customer(
            id="cust-alpha-1",
            tenant_id="tenant-alpha",
            name="Alice Alpha",
            company="Alpha Corp",
            email="alice@alpha.com",
            phone="1234567890"
        )
        self.db.add_all([self.plan_a, self.cust_a])
        self.db.commit()

        # Seed data for Tenant B (Beta)
        self.plan_b = SubscriptionPlan(
            id="plan-b",
            tenant_id="tenant-beta",
            name="Beta Plan",
            code="beta",
            monthly_price=2000,
            annual_price=20000
        )
        self.cust_b = Customer(
            id="cust-beta-1",
            tenant_id="tenant-beta",
            name="Bob Beta",
            company="Beta Corp",
            email="bob@beta.com",
            phone="0987654321"
        )
        self.db.add_all([self.plan_b, self.cust_b])
        self.db.commit()

    def tearDown(self):
        self.db.close()

    def test_tenant_cannot_read_other_tenant_subscriptions(self):
        engine_alpha = SubscriptionLifecycleEngine(self.db, tenant_id="tenant-alpha")
        engine_beta = SubscriptionLifecycleEngine(self.db, tenant_id="tenant-beta")

        class DummyPayload:
            customer_id = "cust-alpha-1"
            plan_id = "plan-a"
            billing_interval = "monthly"
            start_with_trial = False
            auto_renew = True

        sub_alpha = engine_alpha.create(DummyPayload())

        # Alpha can see its subscription
        self.assertEqual(len(engine_alpha.get_all()), 1)
        self.assertIsNotNone(engine_alpha.get_by_id(sub_alpha.id))

        # Beta CANNOT see Alpha's subscription
        self.assertEqual(len(engine_beta.get_all()), 0)
        self.assertIsNone(engine_beta.get_by_id(sub_alpha.id))

    def test_cross_tenant_creation_prevented(self):
        engine_beta = SubscriptionLifecycleEngine(self.db, tenant_id="tenant-beta")

        class IllegalPayload:
            customer_id = "cust-alpha-1"  # Alpha's customer
            plan_id = "plan-b"
            billing_interval = "monthly"
            start_with_trial = False
            auto_renew = True

        # Should raise ValueError because customer does not exist in tenant-beta
        with self.assertRaises(ValueError):
            engine_beta.create(IllegalPayload())

    def test_cross_tenant_payment_processing_blocked(self):
        """CRITICAL: Tenant Beta cannot process a charge against Tenant Alpha's customer or subscription."""
        engine_alpha = SubscriptionLifecycleEngine(self.db, tenant_id="tenant-alpha")
        class Payload:
            customer_id = "cust-alpha-1"
            plan_id = "plan-a"
            billing_interval = "monthly"
            start_with_trial = False
            auto_renew = True

        sub_alpha = engine_alpha.create(Payload())

        # Tenant Beta tries to process payment for Tenant Alpha's customer
        pay_service_beta = PaymentProcessingService(self.db, tenant_id="tenant-beta")
        with self.assertRaises(ValueError):
            pay_service_beta.process_payment(
                subscription_id=sub_alpha.id,
                customer_id="cust-alpha-1",
                amount=1180,
                payment_method={"type": "card", "last4": "1111"}
            )

    def test_cross_tenant_invoice_isolation(self):
        """Ensure invoices generated by Tenant Alpha are completely invisible to Tenant Beta."""
        pay_service_alpha = PaymentProcessingService(self.db, tenant_id="tenant-alpha")
        engine_alpha = SubscriptionLifecycleEngine(self.db, tenant_id="tenant-alpha")
        class Payload:
            customer_id = "cust-alpha-1"
            plan_id = "plan-a"
            billing_interval = "monthly"
            start_with_trial = False
            auto_renew = True

        sub = engine_alpha.create(Payload())
        res = pay_service_alpha.process_payment(
            subscription_id=sub.id,
            customer_id="cust-alpha-1",
            amount=1180,
            payment_method={"type": "card", "last4": "4242"}
        )
        invoice_id = res["invoice"].id

        # Query invoices as tenant Beta
        beta_invoices = self.db.query(Invoice).filter(
            Invoice.id == invoice_id,
            Invoice.tenant_id == "tenant-beta"
        ).first()
        self.assertIsNone(beta_invoices)

if __name__ == '__main__':
    unittest.main()
